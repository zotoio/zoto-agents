"""Bit accounting: what a decoder must receive to reproduce the program."""
from __future__ import annotations

import copy
import json

import numpy as np
import zstandard as zstd

_Z = zstd.ZstdCompressor(level=19)


def _quantize(arr: np.ndarray, q: int):
    if q >= 32:
        return arr.astype(np.float32), arr.astype(np.float32).tobytes()
    lo, hi = float(arr.min()), float(arr.max())
    levels = (1 << q) - 1
    scale = (hi - lo) / levels if hi > lo else 1.0
    ints = np.round((arr - lo) / scale).astype(np.int64) if hi > lo else np.zeros(arr.shape, np.int64)
    dtype = np.uint8 if q <= 8 else (np.uint16 if q <= 16 else np.uint32)
    # store min/scale as float16 per spec; dequantize with the same rounding the decoder sees
    lo16, sc16 = np.float16(lo), np.float16(scale)
    deq = (float(lo16) + ints * float(sc16)).astype(np.float32)
    return deq, np.asarray(ints, dtype).tobytes() + lo16.tobytes() + sc16.tobytes()


def _structure(ir: dict) -> dict:
    d = copy.deepcopy({k: v for k, v in ir.items() if k != "meta"})
    for name, spec in (d.get("params") or {}).items():
        if "value" in spec:
            v = np.asarray(spec["value"])
            spec.pop("value")
            spec["shape"] = list(v.shape)
            spec.pop("init", None)
    return d


def account(ir: dict) -> dict:
    """Return the bit breakdown for an IR (params counted at their declared quant)."""
    struct = json.dumps(_structure(ir), sort_keys=True, separators=(",", ":"))
    struct_bits = 8 * len(_Z.compress(struct.encode()))
    param_bits = 0
    per_param = {}
    n_params = 0
    for name, spec in (ir.get("params") or {}).items():
        n_params += 1
        if "value" not in spec:
            # seeded init is regenerated by the decoder; costs only its spec (already in structure)
            per_param[name] = 0
            continue
        arr = np.asarray(spec["value"], dtype=np.float64)
        q = int(spec.get("quant", 8 if arr.size > 1 else 32))
        _, payload = _quantize(arr, q)
        b = 8 * len(_Z.compress(payload))
        per_param[name] = b
        param_bits += b
    header = 32 * n_params
    total = struct_bits + param_bits + header
    return {"total_bits": total, "total_bytes": (total + 7) // 8, "structure_bits": struct_bits,
            "param_bits": param_bits, "header_bits": header, "per_param_bits": per_param}


def decoded(ir: dict) -> dict:
    """Return a copy of the IR with params replaced by their quantized/dequantized values."""
    d = copy.deepcopy(ir)
    for name, spec in (d.get("params") or {}).items():
        if "value" not in spec:
            continue
        arr = np.asarray(spec["value"], dtype=np.float64)
        q = int(spec.get("quant", 8 if arr.size > 1 else 32))
        deq, _ = _quantize(arr, q)
        spec["value"] = deq.tolist() if arr.ndim else float(deq)
    return d
